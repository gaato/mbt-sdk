"""Codex JSON Schema lowering and RPC metadata tests."""

import json
import copy
import io
from pathlib import Path
import tempfile
import unittest
from contextlib import redirect_stdout

from tools.gen.codex import SchemaBuilder, protocol, run
from tools.gen.diagnostics import GenerationError
from tools.gen.emit_moonbit import emit
from tools.gen.ir import ExternalUnion, Presence, Struct


ROOT = Path(__file__).resolve().parents[3]


class CodexSchemaTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.bundle = json.loads((ROOT / "codex-protocol/spec/schema.json").read_text())
        cls.surface = json.loads((ROOT / "codex-protocol/spec/surface.json").read_text())

    def test_pinned_surface_lowers_without_raw_fallbacks(self):
        builder = SchemaBuilder(self.bundle, self.surface)
        ir = builder.build()
        self.assertFalse(builder.diagnostics)
        self.assertEqual(len(builder.requests), 5)
        self.assertEqual(len(builder.server_requests), 4)
        self.assertNotIn('"gaato/http"', emit(ir)["moon.pkg"])
        self.assertIn("Call[TurnStartResponse]", protocol(builder))

    def test_external_enum_and_nullable_any_json_are_typed(self):
        ir = SchemaBuilder(self.bundle, self.surface).build()
        decision = next(d for d in ir.declarations if d.name == "CommandExecutionApprovalDecision")
        self.assertIsInstance(decision, ExternalUnion)
        self.assertEqual([v.tag for v in decision.variants], [
            "accept", "acceptForSession", "acceptWithExecpolicyAmendment",
            "applyNetworkPolicyAmendment", "decline", "cancel",
        ])
        turn = next(d for d in ir.declarations if d.name == "TurnStartParams")
        self.assertIsInstance(turn, Struct)
        field = next(f for f in turn.fields if f.json_name == "outputSchema")
        self.assertEqual(field.presence, Presence.PRESENCE)
        self.assertEqual(field.type.kind, "Json")

    def test_missing_method_or_response_is_not_silently_omitted(self):
        surface = copy.deepcopy(self.surface)
        surface["requests"]["no/such/method"] = "InitializeResponse"
        with self.assertRaisesRegex(ValueError, "no/such/method"):
            SchemaBuilder(self.bundle, surface)
        surface = copy.deepcopy(self.surface)
        surface["requests"]["initialize"] = "MissingResponse"
        with self.assertRaises(KeyError):
            SchemaBuilder(self.bundle, surface)

    def test_unsupported_union_fails_with_schema_location(self):
        bundle = copy.deepcopy(self.bundle)
        bundle["definitions"]["InitializeParams"]["properties"]["unsupported"] = {
            "oneOf": [{"type": "integer"}, {"type": "number"}]
        }
        with self.assertRaises(GenerationError) as caught:
            SchemaBuilder(bundle, self.surface).build()
        self.assertIn("InitializeParams/properties/unsupported", str(caught.exception))

    def test_schema_literals_remain_literals(self):
        bundle = copy.deepcopy(self.bundle)
        bundle["definitions"]["InitializeParams"]["properties"]["literal"] = {
            "type": "boolean", "const": True, "default": True,
        }
        builder = SchemaBuilder(bundle, self.surface)
        ir = builder.build()
        self.assertIn('.field("literal", true)', emit(ir)["types.mbt"])

    def test_regeneration_detects_changes_and_stale_generated_files(self):
        with tempfile.TemporaryDirectory() as tmp, redirect_stdout(io.StringIO()):
            args = ["--spec", str(ROOT / "codex-protocol/spec/schema.json"),
                    "--surface", str(ROOT / "codex-protocol/spec/surface.json"), "--out", tmp]
            self.assertEqual(run(args), 0)
            self.assertEqual(run(args + ["--check"]), 0)
            (Path(tmp) / "types.mbt").write_text("// GENERATED by tools/gen — DO NOT EDIT.\n")
            self.assertEqual(run(args + ["--check"]), 1)
            self.assertEqual(run(args), 0)
            (Path(tmp) / "stale.mbt").write_text("// GENERATED by tools/gen — DO NOT EDIT.\n")
            self.assertEqual(run(args + ["--check"]), 1)
            self.assertEqual(run(args), 0)
            self.assertFalse((Path(tmp) / "stale.mbt").exists())


if __name__ == "__main__":
    unittest.main()
