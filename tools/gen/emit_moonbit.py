"""Deterministic MoonBit source emission from the generator IR."""

from __future__ import annotations

import json
import re

from .ir import Field, IR, Newtype, Operation, Presence, StringEnum, Struct, TypeRef, UntaggedUnion


HEADER = "// GENERATED by tools/gen — DO NOT EDIT.\n"


def _doc(text: str, fallback: str) -> list[str]:
    cleaned = " ".join((text or fallback).split())
    return ["///|", "///", f"/// {cleaned}"]


def _moon_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _field_type(field: Field) -> str:
    base = field.type.moon_type()
    if field.presence in (Presence.NULLABLE_REQUIRED, Presence.OPTIONAL):
        return base + "?"
    if field.presence == Presence.PRESENCE:
        return f"@sdkjson.Presence[{base}]"
    return base


def _constant(value: object) -> str:
    if isinstance(value, str):
        return _moon_string(value)
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "Json::null()"
    return str(value)


def _is_int64(type_ref: TypeRef) -> bool:
    return type_ref.kind == "Int64"


def _struct(declaration: Struct) -> str:
    lines = _doc(declaration.description, f"Generated representation of {declaration.name}.")
    lines.append(f"pub(all) struct {declaration.name} {{")
    for field in declaration.fields:
        if field.constant is None:
            lines.append(f"  {field.moon_name} : {_field_type(field)}")
    lines.append("}")
    lines.extend(_doc("Encodes this value as JSON.", ""))
    lines.append(f"pub extend {declaration.name} with ToJson::{{to_json}}")
    lines.extend(["///|", f"pub impl ToJson for {declaration.name} with fn to_json(self) {{", "  @sdkjson.ObjBuilder::new()"])
    for field in declaration.fields:
        if field.constant is not None:
            lines.append(f"  .field({_moon_string(field.json_name)}, {_constant(field.constant)})")
        elif field.presence in (Presence.REQUIRED, Presence.NULLABLE_REQUIRED):
            if _is_int64(field.type) and field.presence == Presence.REQUIRED:
                lines.append(f"  .field({_moon_string(field.json_name)}, json_int64_to_json(self.{field.moon_name}))")
            else:
                lines.append(f"  .field({_moon_string(field.json_name)}, self.{field.moon_name})")
        elif field.presence == Presence.OPTIONAL:
            lines.append(f"  .opt({_moon_string(field.json_name)}, self.{field.moon_name})")
        else:
            lines.append(f"  .presence({_moon_string(field.json_name)}, self.{field.moon_name})")
    lines.extend(["  .build()", "}"])
    lines.extend(_doc("Decodes this value from JSON.", ""))
    lines.append(f"pub extend {declaration.name} with @json.FromJson::{{from_json}}")
    lines.extend(["///|", f"pub impl @json.FromJson for {declaration.name} with fn from_json(value, path) {{", "  let obj = @sdkjson.expect_object(value, path)", "  {"])
    for field in declaration.fields:
        if field.constant is not None:
            continue
        key = _moon_string(field.json_name)
        path = f"path.add_key({key})"
        if _is_int64(field.type):
            if field.presence == Presence.REQUIRED:
                expression = f"json_int64(@sdkjson.field(obj, {key}, path), {path})"
            elif field.presence in (Presence.OPTIONAL, Presence.NULLABLE_REQUIRED):
                expression = f"decode_optional_int64(obj, {key}, path)"
            else:
                expression = f"decode_presence_int64(obj, {key}, path)"
        elif field.presence in (Presence.REQUIRED, Presence.NULLABLE_REQUIRED):
            expression = f"@sdkjson.field(obj, {key}, path)"
        elif field.presence == Presence.OPTIONAL:
            expression = f"@sdkjson.opt_field(obj, {key}, path)"
        else:
            expression = f"@sdkjson.presence_field(obj, {key}, path)"
        lines.append(f"    {field.moon_name}: {expression},")
    lines.extend(["  }", "}"])
    return "\n".join(lines)


def _string_enum(declaration: StringEnum) -> str:
    lines = _doc(declaration.description, f"Generated string enum {declaration.name}.")
    lines.append(f"pub(all) enum {declaration.name} {{")
    lines.extend(f"  {variant.name}" for variant in declaration.variants)
    lines.append("  Unknown(String)" if declaration.open else "  Custom(String)")
    lines.append("}")
    lines.extend(_doc("Encodes this string enum as JSON.", ""))
    lines.append(f"pub extend {declaration.name} with ToJson::{{to_json}}")
    lines.extend(["///|", f"pub impl ToJson for {declaration.name} with fn to_json(self) {{", "  let raw = match self {"])
    lines.extend(f"    {variant.name} => {_moon_string(variant.value)}" for variant in declaration.variants)
    tail = "Unknown(raw)" if declaration.open else "Custom(raw)"
    lines.extend([f"    {tail} => raw", "  }", "  raw.to_json()", "}"])
    lines.extend(_doc("Decodes this string enum from JSON.", ""))
    lines.append(f"pub extend {declaration.name} with @json.FromJson::{{from_json}}")
    lines.extend(["///|", f"pub impl @json.FromJson for {declaration.name} with fn from_json(value, path) {{", "  @sdkjson.open_string(", "    value,", "    path,", "    raw => {"])
    lines.append("      match raw {")
    lines.extend(f"        {_moon_string(variant.value)} => Some({variant.name})" for variant in declaration.variants)
    lines.extend(["        _ => None", "      }", "    },"])
    constructor = "raw => Unknown(raw)," if declaration.open else "raw => Custom(raw),"
    lines.extend([f"    {constructor}", "  )", "}"])
    return "\n".join(lines)


def _shape_guard(shape: str, value: str) -> str:
    if shape == "string":
        return f"{value} is String(_)"
    if shape == "number":
        return f"{value} is Number(_, ..)"
    if shape == "boolean":
        return f"{value} is Boolean(_)"
    if shape == "object":
        return f"{value} is Object(_)"
    if shape.startswith("array:"):
        inner = shape[len("array:") :]
        nested = _shape_guard(inner, "item")
        return f"json_array_matches({value}, item => {nested})"
    return "false"


def _union(declaration: UntaggedUnion) -> str:
    lines = _doc(declaration.description, f"Generated untagged union {declaration.name}.")
    lines.append(f"pub(all) enum {declaration.name} {{")
    lines.extend(f"  {variant.name}({variant.type.moon_type()})" for variant in declaration.variants)
    lines.append("}")
    lines.extend(_doc("Encodes this union as JSON.", ""))
    lines.append(f"pub extend {declaration.name} with ToJson::{{to_json}}")
    lines.extend(["///|", f"pub impl ToJson for {declaration.name} with fn to_json(self) {{", "  match self {"])
    lines.extend(f"    {variant.name}(value) => value.to_json()" for variant in declaration.variants)
    lines.extend(["  }", "}"])
    lines.extend(_doc("Decodes this union from JSON.", ""))
    lines.append(f"pub extend {declaration.name} with @json.FromJson::{{from_json}}")
    lines.extend(["///|", f"pub impl @json.FromJson for {declaration.name} with fn from_json(value, path) {{"])
    for variant in declaration.variants:
        lines.extend([f"  if {_shape_guard(variant.shape, 'value')} {{", f"    let decoded : {variant.type.moon_type()} = @json.from_json(value, path~)", f"    return {variant.name}(decoded)", "  }"])
    lines.extend([f"  raise @json.JsonDecodeError((path, {_moon_string('JSON shape does not match any ' + declaration.name + ' variant')}))", "}"])
    return "\n".join(lines)


def _newtype(declaration: Newtype) -> str:
    lines = _doc(declaration.description, f"Generated newtype {declaration.name}.")
    lines.append(f"pub(all) struct {declaration.name}({declaration.inner.moon_type()})")
    lines.extend(_doc("Encodes this newtype as JSON.", ""))
    lines.append(f"pub extend {declaration.name} with ToJson::{{to_json}}")
    lines.extend(["///|", f"pub impl ToJson for {declaration.name} with fn to_json(self) {{", "  self.0.to_json()", "}"])
    lines.extend(_doc("Decodes this newtype from JSON.", ""))
    lines.append(f"pub extend {declaration.name} with @json.FromJson::{{from_json}}")
    lines.extend(["///|", f"pub impl @json.FromJson for {declaration.name} with fn from_json(value, path) {{", f"  let inner : {declaration.inner.moon_type()} = @json.from_json(value, path~)", f"  {declaration.name}(inner)", "}"])
    return "\n".join(lines)


HELPERS = r'''///|
fn parse_plain_int64(text : String) -> Int64? {
  if text.length() == 0 {
    return None
  }
  let negative = text[0] == '-'
  let digits_start = if negative { 1 } else { 0 }
  if digits_start == text.length() {
    return None
  }
  for index in digits_start..<text.length() {
    if text[index] < '0' || text[index] > '9' {
      return None
    }
  }
  let mut significant_start = digits_start
  while significant_start < text.length() && text[significant_start] == '0' {
    significant_start += 1
  }
  if significant_start == text.length() {
    return Some(0L)
  }
  let significant_length = text.length() - significant_start
  let limit = if negative {
    "9223372036854775808"
  } else {
    "9223372036854775807"
  }
  if significant_length > limit.length() {
    return None
  }
  if significant_length == limit.length() {
    for offset in 0..<significant_length {
      let digit = text[significant_start + offset]
      let boundary = limit[offset]
      if digit > boundary {
        return None
      }
      if digit < boundary {
        break
      }
    }
  }
  let mut result = 0L
  for index in significant_start..<text.length() {
    let digit = (text[index] - '0').to_int().to_int64()
    if negative {
      result = result * 10L - digit
    } else {
      result = result * 10L + digit
    }
  }
  Some(result)
}

///|
fn is_plain_integer(text : String) -> Bool {
  if text.length() == 0 {
    return false
  }
  let start = if text[0] == '-' { 1 } else { 0 }
  if start == text.length() {
    return false
  }
  for index in start..<text.length() {
    if text[index] < '0' || text[index] > '9' {
      return false
    }
  }
  true
}

///|
fn json_int64(
  value : Json,
  path : @json.JsonPath,
) -> Int64 raise @json.JsonDecodeError {
  guard value is Number(raw, repr~) else {
    raise @json.JsonDecodeError((path, "expected JSON number for Int64"))
  }
  if repr is Some(text) && is_plain_integer(text) {
    match parse_plain_int64(text) {
      Some(value) => return value
      None =>
        raise @json.JsonDecodeError(
          (path, "JSON number is outside Int64 range"),
        )
    }
  }
  if raw.is_nan() ||
    raw < -9223372036854775808.0 ||
    raw >= 9223372036854775808.0 {
    raise @json.JsonDecodeError((path, "JSON number is outside Int64 range"))
  }
  let result = raw.to_int64()
  if result.to_double() != raw {
    raise @json.JsonDecodeError((path, "expected integral JSON number"))
  }
  result
}
'''


INT64_TO_JSON_HELPER = r'''///|
fn json_int64_to_json(value : Int64) -> Json {
  try! @json.parse(value.to_string())
}'''


OPTIONAL_INT64_HELPER = r'''///|
fn decode_optional_int64(
  obj : Map[String, Json],
  key : String,
  path : @json.JsonPath,
) -> Int64? raise @json.JsonDecodeError {
  let raw : Json? = @sdkjson.opt_field(obj, key, path)
  match raw {
    Some(value) => Some(json_int64(value, path.add_key(key)))
    None => None
  }
}'''


PRESENCE_INT64_HELPER = r'''///|
fn decode_presence_int64(
  obj : Map[String, Json],
  key : String,
  path : @json.JsonPath,
) -> @sdkjson.Presence[Int64] raise @json.JsonDecodeError {
  let raw : @sdkjson.Presence[Json] = @sdkjson.presence_field(obj, key, path)
  match raw {
    @sdkjson.Value(value) => @sdkjson.Value(json_int64(value, path.add_key(key)))
    @sdkjson.Absent => @sdkjson.Absent
    @sdkjson.Null => @sdkjson.Null
  }
}'''


def _path_expression(operation: Operation) -> str:
    parameters = {"{" + item.json_name + "}": item for item in operation.parameters if item.location == "path"}
    parts = re.split(r"(\{[^}]+\})", operation.path)
    expressions: list[str] = []
    for part in parts:
        if not part:
            continue
        if part in parameters:
            expressions.append(f"percent_encode(parameter_value({parameters[part].moon_name}))")
        else:
            expressions.append(_moon_string(part))
    return " + ".join(expressions) if expressions else '""'


def _operation(operation: Operation) -> str:
    request_name = operation.moon_name + "_request"
    decode_name = operation.moon_name + "_decode"
    required = [parameter for parameter in operation.parameters if parameter.required]
    optional = [parameter for parameter in operation.parameters if not parameter.required]
    parameters = [f"{parameter.moon_name} : {parameter.type.moon_type()}" for parameter in required]
    if operation.request_type is not None:
        parameters.append(f"body : {operation.request_type.moon_type()}")
    parameters.extend(f"{parameter.moon_name}? : {parameter.type.moon_type()}" for parameter in optional)
    fallback = f"Builds the {operation.operation_id} request."
    if operation.response_type is None:
        fallback += " The caller handles the response as @http.Response."
    description = " ".join((operation.description, "The caller handles the response as @http.Response." if operation.response_type is None else "")).strip()
    lines = _doc(description, fallback)
    lines.append(f"pub fn {request_name}({', '.join(parameters)}) -> @http.Request {{")
    query_parameters = [parameter for parameter in operation.parameters if parameter.location == "query"]
    if query_parameters:
        lines.append(f"  let mut url = {_path_expression(operation)}")
        for parameter in query_parameters:
            name = _moon_string(parameter.json_name)
            if parameter.type.kind == "array":
                if parameter.required:
                    lines.extend([f"  for value in {parameter.moon_name} {{", f"    url = append_query(url, {name}, parameter_value(value))", "  }"])
                else:
                    lines.extend([f"  match {parameter.moon_name} {{", "    Some(values) =>", "      for value in values {", f"        url = append_query(url, {name}, parameter_value(value))", "      }", "    None => ()", "  }"])
            elif parameter.required:
                lines.append(f"  url = append_query(url, {name}, parameter_value({parameter.moon_name}))")
            else:
                lines.extend([f"  match {parameter.moon_name} {{", f"    Some(value) => url = append_query(url, {name}, parameter_value(value))", "    None => ()", "  }"])
        path_expression = "url"
    else:
        path_expression = _path_expression(operation)
    constructor = {"GET": "get", "POST": "post", "PUT": "put", "PATCH": "patch", "DELETE": "delete"}.get(operation.method)
    if constructor:
        expression = f"@http.Request::{constructor}({path_expression})"
    else:
        expression = f"@http.Request::new({_moon_string(operation.method)}, {path_expression})"
    if operation.request_type is not None:
        expression += ".json_body(body.to_json())"
    header_parameters = [parameter for parameter in operation.parameters if parameter.location == "header"]
    if header_parameters:
        lines.append(f"  let mut request = {expression}")
        for parameter in header_parameters:
            name = _moon_string(parameter.json_name)
            if parameter.type.kind == "array":
                value = f'{parameter.moon_name}.map(value => parameter_value(value)).join(",")'
            else:
                value = f"parameter_value({parameter.moon_name})"
            if parameter.required:
                lines.append(f"  request = request.header({name}, {value})")
            else:
                if parameter.type.kind == "array":
                    optional_value = 'values.map(value => parameter_value(value)).join(",")'
                else:
                    optional_value = "parameter_value(value)"
                lines.extend([f"  match {parameter.moon_name} {{", f"    Some(value{'s' if parameter.type.kind == 'array' else ''}) => request = request.header({name}, {optional_value})", "    None => ()", "  }"])
        lines.extend(["  request", "}"])
    else:
        lines.extend([f"  {expression}", "}"])
    if operation.response_type is not None:
        lines.extend(_doc(f"Decodes a successful {operation.operation_id} response.", ""))
        lines.extend([f"pub fn {decode_name}(", "  response : @http.Response,", f") -> {operation.response_type.moon_type()} raise @runtime.SdkError {{", "  decode_response(response)", "}"])
    return "\n".join(lines)


PERCENT_ENCODE_HELPER = r'''///|
fn percent_encode(value : String) -> String {
  let hex = b"0123456789ABCDEF"
  let output : Array[Byte] = []
  for byte in @utf8.encode(value) {
    let code = byte.to_int()
    if (code >= 65 && code <= 90) ||
      (code >= 97 && code <= 122) ||
      (code >= 48 && code <= 57) ||
      byte == b'-' ||
      byte == b'.' ||
      byte == b'_' ||
      byte == b'~' {
      output.push(byte)
    } else {
      output.push(b'%')
      output.push(hex[code >> 4])
      output.push(hex[code & 15])
    }
  }
  try! @utf8.decode(Bytes::from_array(output))
}'''


PARAMETER_VALUE_HELPER = r'''///|
fn[T : ToJson] parameter_value(value : T) -> String {
  match value.to_json() {
    String(value) => value
    True => "true"
    False => "false"
    Number(value, repr~) =>
      match repr {
        Some(text) => text
        None => value.to_string()
      }
    other => other.stringify()
  }
}'''


APPEND_QUERY_HELPER = r'''///|
fn append_query(url : String, name : String, value : String) -> String {
  let separator = if url.contains("?") { "&" } else { "?" }
  url + separator + percent_encode(name) + "=" + percent_encode(value)
}'''


DECODE_HELPERS = r'''///|
fn parse_json_body(body : Bytes) -> Json raise {
  @json.parse(@utf8.decode(body))
}

///|
fn[T : @json.FromJson] decode_response(
  response : @http.Response,
) -> T raise @runtime.SdkError {
  @json.from_json(parse_json_body(response.body)) catch {
    error =>
      raise @runtime.Decode(message=error.to_string(), body=response.body)
  }
}'''


def emit(ir: IR) -> dict[str, str]:
    declarations: list[str] = []
    has_int64 = False
    has_required_int64 = False
    has_union = False
    has_optional_int64 = False
    has_presence_int64 = False
    for declaration in ir.declarations:
        if isinstance(declaration, Struct):
            declarations.append(_struct(declaration))
            has_int64 = has_int64 or any(field.type.kind == "Int64" for field in declaration.fields)
            has_required_int64 = has_required_int64 or any(
                field.type.kind == "Int64" and field.presence == Presence.REQUIRED
                for field in declaration.fields
            )
            has_optional_int64 = has_optional_int64 or any(
                field.type.kind == "Int64" and field.presence in (Presence.OPTIONAL, Presence.NULLABLE_REQUIRED)
                for field in declaration.fields
            )
            has_presence_int64 = has_presence_int64 or any(
                field.type.kind == "Int64" and field.presence == Presence.PRESENCE
                for field in declaration.fields
            )
        elif isinstance(declaration, StringEnum):
            declarations.append(_string_enum(declaration))
        elif isinstance(declaration, UntaggedUnion):
            declarations.append(_union(declaration))
            has_union = True
        elif isinstance(declaration, Newtype):
            declarations.append(_newtype(declaration))
    helpers: list[str] = []
    if has_int64:
        helpers.append(HELPERS)
    if has_required_int64:
        helpers.append(INT64_TO_JSON_HELPER)
    if has_optional_int64:
        helpers.append(OPTIONAL_INT64_HELPER)
    if has_presence_int64:
        helpers.append(PRESENCE_INT64_HELPER)
    if has_union and any(
        variant.shape.startswith("array:")
        for declaration in ir.declarations
        if isinstance(declaration, UntaggedUnion)
        for variant in declaration.variants
    ):
        helpers.insert(0, '''///|
fn json_array_matches(
  value : Json,
  predicate : (Json) -> Bool,
) -> Bool {
  match value {
    Array(items) => items.length() > 0 && items.all(predicate)
    _ => false
  }
}''')
    types = HEADER + "\n\n".join(helpers + declarations) + "\n"
    operation_sources = [_operation(operation) for operation in ir.operations]
    operation_helpers: list[str] = []
    if any(operation.parameters for operation in ir.operations):
        operation_helpers.append(PARAMETER_VALUE_HELPER)
    if any(parameter.location in {"path", "query"} for operation in ir.operations for parameter in operation.parameters):
        operation_helpers.append(PERCENT_ENCODE_HELPER)
    if any(parameter.location == "query" for operation in ir.operations for parameter in operation.parameters):
        operation_helpers.append(APPEND_QUERY_HELPER)
    if any(operation.response_type is not None for operation in ir.operations):
        operation_helpers.append(DECODE_HELPERS)
    operations = HEADER + "\n\n".join(operation_helpers + operation_sources) + "\n"
    # Import only what the emitted code references: `--deny-warn` rejects unused packages.
    body = types + operations
    imports = ['  "gaato/http",']
    if "@runtime." in body:
        imports.append('  "gaato/sdk-runtime" @runtime,')
    if "@sdkjson." in body:
        imports.append('  "gaato/sdk-runtime/json" @sdkjson,')
    if "@utf8." in body:
        imports.append('  "moonbitlang/core/encoding/utf8",')
    if "@json." in body:
        imports.append('  "moonbitlang/core/json",')
    moon_pkg = HEADER + "import {\n" + "\n".join(imports) + "\n}\n"
    return {"moon.pkg": moon_pkg, "types.mbt": types, "operations.mbt": operations}
